/*
 * Embeds Languages/*.json into main.js (BUILTIN_LANGUAGES), so translations
 * work for users who install only main.js, manifest.json and styles.css
 * from a GitHub release. Files in the plugin's Languages folder still
 * override and extend the embedded strings at runtime.
 */
const fs = require('fs');
const path = require('path');

const root = process.cwd();
const mainFile = path.join(root, 'main.js');
const languagesDir = path.join(root, 'Languages');
const markerRegex = /\/\/ BUILTIN-LANGUAGES-START[\s\S]*?\/\/ BUILTIN-LANGUAGES-END/;

const languages = {};
if (fs.existsSync(languagesDir)) {
  for (const file of fs.readdirSync(languagesDir).sort()) {
    if (!file.toLowerCase().endsWith('.json')) continue;
    const parsed = JSON.parse(fs.readFileSync(path.join(languagesDir, file), 'utf8'));
    const code = String(parsed.code || file.replace(/\.json$/i, ''))
      .trim()
      .toLowerCase();
    if (!code || code === 'en') continue;
    languages[code] = {
      name: String(parsed.name || code),
      strings: parsed.strings && typeof parsed.strings === 'object' ? parsed.strings : {},
    };
  }
}

const source = fs.readFileSync(mainFile, 'utf8');
if (!markerRegex.test(source)) {
  console.error('BUILTIN-LANGUAGES markers not found in main.js');
  process.exit(1);
}

const block =
  '// BUILTIN-LANGUAGES-START\n' +
  '// Generated by scripts/embed-languages.js from Languages/*.json. Do not edit by hand.\n' +
  `const BUILTIN_LANGUAGES = ${JSON.stringify(languages, null, 2)};\n` +
  '// BUILTIN-LANGUAGES-END';

fs.writeFileSync(
  mainFile,
  source.replace(markerRegex, () => block),
  'utf8'
);
console.log(`Embedded languages: ${Object.keys(languages).join(', ') || '(none)'}`);
