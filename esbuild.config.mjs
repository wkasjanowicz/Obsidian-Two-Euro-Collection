/*
 * Builds main.js (the file Obsidian loads) from the sources in src/.
 *   npm run build        – one-off build
 *   npm run dev          – rebuild on every change
 * main.js is generated: edit files in src/, never main.js directly.
 */
import esbuild from 'esbuild';
import { builtinModules } from 'node:module';

const watch = process.argv.includes('--watch');

const options = {
  entryPoints: ['src/main.js'],
  outfile: 'main.js',
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  external: [
    'obsidian',
    'electron',
    '@codemirror/*',
    '@lezer/*',
    ...builtinModules,
    ...builtinModules.map((name) => `node:${name}`),
  ],
  // Readable output: Obsidian reviewers and users can inspect main.js.
  minify: false,
  charset: 'utf8',
  sourcemap: watch ? 'inline' : false,
  treeShaking: true,
  legalComments: 'inline',
  logLevel: 'info',
  banner: {
    js: '/* 2 Euro Collection – generated by esbuild from src/. Do not edit this file directly. */',
  },
};

if (watch) {
  const context = await esbuild.context(options);
  await context.watch();
} else {
  await esbuild.build(options);
}
